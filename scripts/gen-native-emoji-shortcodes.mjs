#!/usr/bin/env node
/**
 * Codegen: EMOJI_SHORTCODES (apps/web/src/app/lib/emoji-shortcodes.ts)
 *        → Swift table (apps/conclave-skip/Sources/Conclave/Features/Meeting/Chat/EmojiShortcodeTable.swift)
 *
 * The web table is the single source of truth for chat :name: shortcuts on web
 * and native. Re-run after editing emoji-shortcodes.ts:
 *
 *   node scripts/gen-native-emoji-shortcodes.mjs
 *
 * `--check` fails when the Swift table is stale, or when the web matching
 * patterns change, because EmojiShortcodes.swift ports those patterns by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import vm from "node:vm";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(repoRoot, "apps/web/src/app/lib/emoji-shortcodes.ts");
const outPath = resolve(
  repoRoot,
  "apps/conclave-skip/Sources/Conclave/Features/Meeting/Chat/EmojiShortcodeTable.swift",
);

const PORTED_PATTERNS = {
  SHORTCODE_PATTERN: "/:([a-z0-9_+-]{1,40}):/gi",
  DIRECT_MESSAGE_PREFIX_PATTERN: "/^(\\s*(?:@\\S+|\\/dm\\s+\\S+))([\\s\\S]*)$/i",
};

function objectLiteral(source, name) {
  const marker = `const ${name}`;
  const markerIndex = source.indexOf(marker);
  if (markerIndex === -1) throw new Error(`Could not find ${marker} in ${sourcePath}`);
  const start = source.indexOf("{", source.indexOf("=", markerIndex));
  let depth = 0;
  let quote = null;
  let escaped = false;
  let lineComment = false;
  for (let index = start; index < source.length; index += 1) {
    const char = source[index];
    if (lineComment) {
      if (char === "\n") lineComment = false;
      continue;
    }
    if (quote) {
      if (escaped) escaped = false;
      else if (char === "\\") escaped = true;
      else if (char === quote) quote = null;
      continue;
    }
    if (char === "/" && source[index + 1] === "/") {
      lineComment = true;
      continue;
    }
    if (char === "\"" || char === "'") {
      quote = char;
      continue;
    }
    if (char === "{") depth += 1;
    if (char === "}") {
      depth -= 1;
      if (depth === 0) return source.slice(start, index + 1);
    }
  }
  throw new Error(`Could not parse the ${name} object literal`);
}

function patternSource(source, name) {
  const match = source.match(new RegExp(`const ${name} =\\s*(\\/.+\\/[a-z]*);`));
  if (!match) throw new Error(`Could not find ${name} in ${sourcePath}`);
  return match[1];
}

const source = readFileSync(sourcePath, "utf8");
const problems = [];
for (const [name, expected] of Object.entries(PORTED_PATTERNS)) {
  const actual = patternSource(source, name);
  if (actual !== expected) {
    problems.push(
      `${name} changed to ${actual}. Port the change to EmojiShortcodes.swift, then update PORTED_PATTERNS in this script.`,
    );
  }
}

const table = vm.runInNewContext(`(${objectLiteral(source, "EMOJI_SHORTCODES")})`, Object.create(null));
const entries = Object.entries(table);
for (const [name, emoji] of entries) {
  if (!/^[a-z0-9_+-]{1,40}$/.test(name)) problems.push(`Shortcode ${JSON.stringify(name)} can never match.`);
  if (typeof emoji !== "string" || emoji.length === 0) problems.push(`Shortcode ${name} has no emoji.`);
}

const lines = entries.map(([name, emoji]) => `        ${JSON.stringify(name)}: ${JSON.stringify(emoji)},`);
const generated = [
  "// GENERATED by scripts/gen-native-emoji-shortcodes.mjs from apps/web/src/app/lib/emoji-shortcodes.ts. Do not edit.",
  "",
  "enum EmojiShortcodeTable {",
  "    static let emoji: [String: String] = [",
  ...lines,
  "    ]",
  "}",
  "",
].join("\n");

if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {}
  if (current !== generated) {
    console.error(`Native emoji shortcodes are out of date: ${outPath}\nRun node scripts/gen-native-emoji-shortcodes.mjs to update them.`);
    process.exit(1);
  }
  console.log(`Native emoji shortcodes are up to date (${entries.length} shortcodes).`);
} else {
  writeFileSync(outPath, generated);
  console.log(`Generated ${outPath} (${entries.length} shortcodes).`);
}
