const capitalized = (name) => name[0].toUpperCase() + name.slice(1);

function expectKeys(value, keys, path) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${path} must be an object`);
  }
  const actual = Object.keys(value);
  const missing = keys.filter((key) => !Object.hasOwn(value, key));
  const extra = actual.filter((key) => !keys.includes(key));
  if (missing.length || extra.length) {
    throw new Error(`${path}: missing [${missing.join(", ")}], unexpected [${extra.join(", ")}]`);
  }
}

function argb(value, path) {
  if (!Number.isInteger(value) || value < 0 || value > 0xFFFFFFFF) {
    throw new Error(`${path} must be an unsigned 32-bit ARGB integer`);
  }
  return value.toString(16).toUpperCase().padStart(8, "0");
}

function colorSet(appearances) {
  return JSON.stringify({
    colors: appearances.map(([value, variants]) => ({
      ...(variants.length ? { appearances: variants.map(([appearance, name]) => ({ appearance, value: name })) } : {}),
      color: {
        "color-space": "srgb",
        components: {
          alpha: ((value >>> 24) / 255).toFixed(6),
          blue: `0x${argb(value).slice(6, 8)}`,
          green: `0x${argb(value).slice(4, 6)}`,
          red: `0x${argb(value).slice(2, 4)}`,
        },
      },
      idiom: "universal",
    })),
    info: { author: "xcode", version: 1 },
  }, null, 2) + "\n";
}

/** Pure rendering API for fixture tests. All validation finishes before any I/O. */
export function renderNativeTokens(tokens = native) {
  expectKeys(tokens, ["brand", "neutral", "status", "ios", "android", "space", "radius", "avatar"], "native");
  expectKeys(tokens.status, ["light", "dark"], "native.status");
  expectKeys(tokens.ios, ["app", "inCall", "game"], "native.ios");
  expectKeys(tokens.android, ["light", "dark", "inCall", "extended"], "native.android");
  expectKeys(tokens.avatar, ["palette", "ring", "tongue"], "native.avatar");
  const lines = [`// ${generatedNotice}`, "import Foundation", "", "enum DesignTokens {"];
  const names = new Set();
  function constant(name, type, value) {
    if (names.has(name)) throw new Error(`Duplicate generated token name: ${name}`);
    names.add(name);
    lines.push(`    static let ${name}: ${type} = ${value}`);
  }
  function colors(path, value, keys, nameFor) {
    expectKeys(value, keys, `native.${path}`);
    for (const key of keys) constant(nameFor(key), "Int64", `0x${argb(value[key], `native.${path}.${key}`)}`);
    lines.push("");
  }
  colors("brand", tokens.brand, brandKeys, (key) => key);
  colors("neutral", tokens.neutral, neutralKeys, (key) => `neutral${capitalized(key)}`);
  for (const mode of ["light", "dark"]) {
    colors(`status.${mode}`, tokens.status[mode], statusKeys, (key) => `${key}${capitalized(mode)}`);
  }
  colors("ios.app", tokens.ios.app, iosAppKeys, (key) => `iosApp${capitalized(key)}`);
  colors("ios.inCall", tokens.ios.inCall, iosInCallKeys, (key) => `iosInCall${capitalized(key)}`);
  colors("ios.game", tokens.ios.game, iosGameKeys, (key) => `iosGame${capitalized(key)}`);
  for (const mode of ["light", "dark", "inCall"]) {
    colors(`android.${mode}`, tokens.android[mode], androidRoles, (key) => `android${capitalized(mode)}${capitalized(key)}`);
  }
  colors("android.extended", tokens.android.extended, extendedKeys, (key) => `androidExtended${capitalized(key)}`);
  for (const [group, keys, nameFor] of [
    ["space", spaceKeys, (key) => key],
    ["radius", radiusKeys, (key) => `radius${capitalized(key)}`],
  ]) {
    expectKeys(tokens[group], keys, `native.${group}`);
    for (const key of keys) {
      const value = tokens[group][key];
      if (typeof value !== "number" || !Number.isFinite(value) || value <= 0) {
        throw new Error(`native.${group}.${key} must be a finite positive metric`);
      }
      constant(nameFor(key), "Double", String(value));
    }
    lines.push("");
  }
  if (!Array.isArray(tokens.avatar.palette) || tokens.avatar.palette.length !== 16) {
    throw new Error("native.avatar.palette must contain 16 ARGB colors in identity order");
  }
  const avatarColors = Array.from(tokens.avatar.palette, (value, i) => `0x${argb(value, `native.avatar.palette[${i}]`)}`);
  constant("avatarPalette", "[Int64]", `[${avatarColors.join(", ")}]`);
  constant("avatarRing", "Int64", `0x${argb(tokens.avatar.ring, "native.avatar.ring")}`);
  constant("avatarTongue", "Int64", `0x${argb(tokens.avatar.tongue, "native.avatar.tongue")}`);
  lines.push("}", "");

  const app = tokens.ios.app;
  const outputs = new Map([
    [`${nativeRoot}/Sources/Conclave/DesignSystem/DesignTokens.swift`, lines.join("\n")],
    [`${nativeRoot}/Darwin/Assets.xcassets/AccentColor.colorset/Contents.json`, colorSet([
      [app.coralTextLight, []],
      [app.coralTextDark, [["luminosity", "dark"]]],
      [app.coralTextLightHighContrast, [["contrast", "high"]]],
      [app.coralTextDarkHighContrast, [["luminosity", "dark"], ["contrast", "high"]]],
    ])],
    [`${nativeRoot}/Darwin/Assets.xcassets/LaunchBackground.colorset/Contents.json`, colorSet([
      [app.launchBackgroundLight, []],
      [app.launchBackgroundDark, [["luminosity", "dark"]]],
    ])],
  ]);
  for (const [folder, mode] of [["values", "light"], ["values-night", "dark"]]) {
    const resources = [
      ["conclave_window_background", tokens.android[mode].background],
      // S70 SX8: notification accent (Notification.setColor) from the scheme's primary; follows night mode on re-post.
      ["sys_notification_accent", tokens.android[mode].primary],
      // S2-T2 (EF-2): the launch theme accent, so View-based UI (WebView handles, system dialogs) follows the scheme.
      ["conclave_primary", tokens.android[mode].primary],
      ["conclave_on_primary", tokens.android[mode].onPrimary],
    ];
    // S70 11 d: the adaptive icon tile is the stage color in every appearance, so it has no night variant.
    if (mode === "light") resources.push(["ic_launcher_background", tokens.android.extended.stage]);
    outputs.set(`${nativeRoot}/Android/app/src/main/res/${folder}/colors.xml`,
      `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${generatedNotice} -->\n<resources>\n` +
      resources.map(([name, value]) => `    <color name="${name}">#${argb(value, `colors.xml ${name}`)}</color>\n`).join("") +
      "</resources>\n");
  }
  return outputs;
}

/** Check mode only reads, including when files/directories do not exist. */
export async function generateNativeTokens({ outputRoot = repoRoot, check = false, tokens = native } = {}) {
  const outputs = renderNativeTokens(tokens);
  const drift = [];
  for (const [relativePath, expected] of outputs) {
    const path = resolve(outputRoot, relativePath);
    let actual;
    try {
      actual = await readFile(path, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (actual === expected) continue;
    drift.push(relativePath);
    if (!check) {
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, expected, "utf8");
    }
  }
  return { drift, outputCount: outputs.size };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { values } = parseArgs({ options: {
      check: { type: "boolean", default: false },
      "output-root": { type: "string", default: repoRoot },
    } });
    const result = await generateNativeTokens({ outputRoot: values["output-root"], check: values.check });
    if (values.check && result.drift.length) {
      console.error(`Native token drift:\n${result.drift.map((path) => `  ${path}`).join("\n")}\nRun: node ${generator}`);
      process.exitCode = 1;
    } else {
      console.log(`Native tokens: ${result.outputCount} outputs ${values.check ? "match" : "generated"}.`);
    }
  } catch (error) {
    console.error(`Native token generation failed: ${error.message}`);
    process.exitCode = 1;
  }
}
