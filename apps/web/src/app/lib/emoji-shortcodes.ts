const SHORTCODE_PATTERN = /:([a-z0-9_+-]{1,40}):/gi;

export function getEmojiForShortcode(name: string): string | undefined {
  const key = name.toLowerCase();
  return Object.prototype.hasOwnProperty.call(EMOJI_SHORTCODES, key)
    ? EMOJI_SHORTCODES[key]
    : undefined;
}

export function replaceEmojiShortcodesInText(text: string): string {
  if (!text.includes(":")) return text;
  let result = "";
  let cursor = 0;
  SHORTCODE_PATTERN.lastIndex = 0;
  let match: RegExpExecArray | null;
  while ((match = SHORTCODE_PATTERN.exec(text)) !== null) {
    const emoji = getEmojiForShortcode(match[1]);
    if (!emoji) {
      SHORTCODE_PATTERN.lastIndex = match.index + match[0].length - 1;
      continue;
    }
    result += text.slice(cursor, match.index) + emoji;
    cursor = match.index + match[0].length;
  }
  return cursor === 0 ? text : result + text.slice(cursor);
}

export function replaceEmojiShortcodes(content: string): string {
  if (!content.includes(":")) return content;
  return getChatMessageSegments(content)
    .map((segment) =>
      segment.href ? segment.text : replaceEmojiShortcodesInText(segment.text),
    )
    .join("");
}

const DIRECT_MESSAGE_PREFIX_PATTERN = /^(\s*(?:@\S+|\/dm\s+\S+))([\s\S]*)$/i;

export function replaceEmojiShortcodesInMessage(content: string): string {
  const match = content.match(DIRECT_MESSAGE_PREFIX_PATTERN);
  if (!match) return replaceEmojiShortcodes(content);
  return match[1] + replaceEmojiShortcodes(match[2] ?? "");
}
