#!/usr/bin/env python3
"""Generate/check bundled chess templates from pinned MIT-licensed SVG paths. No network or dependencies."""

import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr


HERE = Path(__file__).resolve().parent
PACKAGE = HERE.parents[1]
KINDS = ("king", "queen", "rook", "bishop", "knight", "pawn")
SVG = "http://www.w3.org/2000/svg"
ANDROID = "http://schemas.android.com/apk/res/android"


def verified_bytes(entry):
    data = (HERE / entry["path"]).read_bytes()
    if hashlib.sha256(data).hexdigest() != entry["sha256"]:
        raise ValueError(f"Canonical input changed: {entry['path']}")
    return data


def outputs():
    manifest = json.loads((HERE / "provenance.json").read_text())
    if tuple(p["kind"] for p in manifest["pieces"]) != KINDS:
        raise ValueError("Expected all six distinct chess piece kinds")
    license_bytes = verified_bytes(manifest["license"])
    result = {
        PACKAGE / "Sources/Conclave/Resources/TablerChess-LICENSE.txt": license_bytes,
        PACKAGE / "Android/app/src/main/assets/TablerChess-LICENSE.txt": license_bytes,
    }
    attribution = (
        "Conclave chess artwork: Tabler Icons (filled chess set)\n"
        "Copyright (c) 2020-2026 Paweł Kuna. Licensed under the MIT License.\n"
        f"Upstream: {manifest['repository']}/tree/{manifest['commit']}/icons/filled\n"
        "The pawn uses chess.svg; the other pieces use chess-{kind}.svg.\n"
        "Original path geometry is unchanged. Conclave converts the SVGs to native templates,\n"
        "applies its paper/ink colors and draws a contrasting outline for each side.\n"
        "Full license: TablerChess-LICENSE.txt\n"
    ).encode()
    result[PACKAGE / "Sources/Conclave/Resources/TablerChess-ATTRIBUTION.txt"] = attribution
    result[PACKAGE / "Android/app/src/main/assets/TablerChess-ATTRIBUTION.txt"] = attribution
    for piece in manifest["pieces"]:
        root = ET.fromstring(verified_bytes(piece))
        if root.tag != f"{{{SVG}}}svg" or root.attrib != {
            "width": "24", "height": "24", "viewBox": "0 0 24 24", "fill": "currentColor"
        }:
            raise ValueError(f"Unsupported SVG root: {piece['path']}")
        paths = []
        for child in root:
            if child.tag != f"{{{SVG}}}path" or set(child.attrib) != {"d"} or not child.attrib["d"]:
                raise ValueError(f"Unsupported SVG child: {piece['path']}")
            paths.append(child.attrib["d"])
        if not paths:
            raise ValueError(f"Empty artwork: {piece['path']}")
        kind = piece["kind"]
        name = "ChessPiece" + kind.capitalize()
        svg = (
            '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="#ffffff">\n'
            '  <!-- Tabler Icons, MIT. See TablerChess-LICENSE.txt and TablerChess-ATTRIBUTION.txt. -->\n'
            + "".join(f"  <path d={quoteattr(d)} />\n" for d in paths)
            + "</svg>\n"
        )
        contents = {
            "images": [{"filename": name + ".svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True, "template-rendering-intent": "template"},
        }
        asset = PACKAGE / f"Darwin/Assets.xcassets/{name}.imageset"
        result[asset / (name + ".svg")] = svg.encode()
        result[asset / "Contents.json"] = (json.dumps(contents, indent=2) + "\n").encode()
        vector = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Tabler Icons, MIT. See assets/TablerChess-LICENSE.txt and TablerChess-ATTRIBUTION.txt. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24" android:autoMirrored="false">\n'
            + "".join(f'    <path android:fillColor="#FFFFFFFF" android:fillType="nonZero" android:pathData={quoteattr(d)} />\n' for d in paths)
            + "</vector>\n"
        )

        if [p.attrib["d"] for p in ET.fromstring(svg)] != paths:
            raise ValueError("SVG path conversion drift")
        if [p.attrib[f"{{{ANDROID}}}pathData"] for p in ET.fromstring(vector)] != paths:
            raise ValueError("VectorDrawable path conversion drift")
        result[PACKAGE / f"Android/app/src/main/res/drawable/chess_piece_{kind}.xml"] = vector.encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="Verify every generated byte without writing")
    mode.add_argument("--write", action="store_true", help="Regenerate only the declared artwork and notices")
    args = parser.parse_args()
    expected = outputs()
    for path, data in expected.items():
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.is_file() or path.read_bytes() != data:
            raise ValueError(f"Missing or stale generated artwork: {path.relative_to(PACKAGE)}")
    print(json.dumps({"mode": "write" if args.write else "check", "canonical_inputs": 7,
                      "piece_kinds": len(KINDS), "side_bindings": len(KINDS) * 2,
                      "generated_files": len(expected), "path_geometry_unchanged": True}))


if __name__ == "__main__":
    main()
